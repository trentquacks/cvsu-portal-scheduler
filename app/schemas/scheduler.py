"""Pydantic schemas for the AI-Driven Enrollment Scheduler API."""

from pydantic import BaseModel, Field, field_validator

from app.config import DAYS, HOURS


class AvailabilityMatrixPayload(BaseModel):
    """Mon-Sat 7:00 AM-8:00 PM binary availability matrix (1=Available, 0=Blocked)."""

    matrix: dict[str, list[int]] = Field(
        ...,
        description="Mapping of day code (M, T, W, TH, F, S) to 13 binary flags for hours 07:00-20:00.",
    )

    @field_validator("matrix")
    @classmethod
    def validate_matrix(cls, value: dict[str, list[int]]) -> dict[str, list[int]]:
        expected_len = len(HOURS)
        normalized: dict[str, list[int]] = {}
        for day in DAYS:
            slots = value.get(day)
            if slots is None:
                normalized[day] = [1] * expected_len
            else:
                if len(slots) != expected_len:
                    raise ValueError(f"Day '{day}' must contain exactly {expected_len} hourly slots.")
                normalized[day] = [1 if int(s) else 0 for s in slots]
        return normalized


class TranscriptUpdateItem(BaseModel):
    """Single course standing update for interactive transcript testing."""

    course_code: str
    status: str = Field(..., pattern="^(PASSED|CREDITED|FAILED|DROPPED|NOT_TAKEN)$")
    grade: str = "-"


class TranscriptUpdateRequest(BaseModel):
    """Batch update of a student's transcript records."""

    updates: list[TranscriptUpdateItem]


class MeetingDTO(BaseModel):
    """Serialized lecture or laboratory weekly meeting block."""

    meeting_type: str
    day: str
    start_hour: int
    end_hour: int
    room: str
    time_range_24h: str
    portal_format: str


class OfferingDTO(BaseModel):
    """Serialized institutional BSCS section offering."""

    offering_id: int
    schedule_code: str
    course_code: str
    course_title: str
    lec_units: int
    lab_units: int
    total_units: int
    section_name: str
    instructor: str
    max_capacity: int
    enrolled_count: int
    seats_remaining: int
    status: str
    is_open: bool
    meetings: list[MeetingDTO]


class CourseEligibilityItem(BaseModel):
    """Result of automated DAG prerequisite validation for one BSCS course."""

    course_id: int
    code: str
    title: str
    lec_units: int
    lab_units: int
    total_units: int
    year_level: int
    semester: str
    major: str
    transcript_status: str  # PASSED | CREDITED | FAILED | DROPPED | NOT_TAKEN
    grade: str
    eligibility: str  # COMPLETED | ELIGIBLE | OVERRIDDEN | LOCKED
    prerequisites: list[str]
    missing_prerequisites: list[str]
    override_reason: str | None = None
    offered_this_sem: bool = False
    open_offerings_count: int = 0


class ConflictLogItem(BaseModel):
    """Structured diagnostic item in the Conflict Report Log."""

    conflict_type: str  # PREREQUISITE_UNMET | CAPACITY_FULL | BLOCKED_TIME_SLOT | TIME_OVERLAP | NO_OFFERING | UNIT_LIMIT
    severity: str = "ERROR"  # ERROR | WARNING
    course_codes: list[str]
    schedule_codes: list[str] = Field(default_factory=list)
    day: str | None = None
    time_range: str | None = None
    message: str


class SwapActionDTO(BaseModel):
    """Individual section change inside a dynamic swap recommendation."""

    course_code: str
    from_schedule_code: str | None = None
    from_section: str | None = None
    to_schedule_code: str
    to_section: str
    reason: str


class SwapRecommendationDTO(BaseModel):
    """Alternative conflict-free schedule produced by the Dynamic Section-Swapping Engine."""

    swap_count: int
    summary: str
    actions: list[SwapActionDTO]
    resulting_offerings: list[OfferingDTO]
    total_units: int
    idle_gap_hours: int
    active_days: int


class RelaxationSuggestion(BaseModel):
    """Minimal blocked availability slot(s) to unblock when schedule is deadlocked."""

    slots_to_unblock: list[dict[str, str | int]]
    description: str
    resulting_offerings: list[OfferingDTO]
    idle_gap_hours: int


class ScheduleOptionDTO(BaseModel):
    """One conflict-free schedule option generated by the OR-Tools CP-SAT engine."""

    rank: int
    label: str
    total_units: int
    total_lec_units: int
    total_lab_units: int
    idle_gap_hours: int
    active_days: int
    offerings: list[OfferingDTO]


class SolveRequest(BaseModel):
    """Input payload for running prerequisite validation + CP-SAT solver + swap diagnostics."""

    course_codes: list[str] = Field(..., min_length=1)
    pinned_offerings: dict[str, str] = Field(
        default_factory=dict,
        description="Optional mapping of course_code -> preferred schedule_code to pin/evaluate.",
    )
    availability_matrix: dict[str, list[int]] | None = None
    max_units: int = Field(default=24, ge=1, le=30)
    max_solutions: int = Field(default=5, ge=1, le=10)


class SolveResponse(BaseModel):
    """Complete response from the CSP Solver and Dynamic Section-Swapping Engine."""

    feasible: bool
    solver_status: str  # OPTIMAL | FEASIBLE | INFEASIBLE | PREREQUISITE_BLOCKED | UNIT_LIMIT_EXCEEDED
    solver_time_ms: float
    selected_courses_count: int
    total_requested_units: int
    max_units: int
    options: list[ScheduleOptionDTO] = Field(default_factory=list)
    conflict_logs: list[ConflictLogItem] = Field(default_factory=list)
    swap_recommendations: list[SwapRecommendationDTO] = Field(default_factory=list)
    relaxation_suggestion: RelaxationSuggestion | None = None
    message: str


class SubmitScheduleRequest(BaseModel):
    """Student submission of a conflict-free generated master schedule to their Adviser."""

    schedule_codes: list[str] = Field(..., min_length=1)
    solver_time_ms: float = 0.0
    idle_gap_hours: int = 0
    conflict_logs: list[dict] = Field(default_factory=list)
    swap_history: list[dict] = Field(default_factory=list)


class SubmitScheduleResponse(BaseModel):
    """Result of submitting a schedule for Academic Adviser review."""

    submission_id: int
    status: str
    total_units: int
    message: str
